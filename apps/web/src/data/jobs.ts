export function getJob(id: string) {
  return jobs.find((job) => job.id === id);
}

/** Distinct values for a job field, in first-seen order — used to build filters from real data. */
export function jobFacet<K extends keyof Job>(key: K): string[] {
  const seen: string[] = [];
  for (const job of jobs) {
    const value = job[key];
    if (typeof value === "string" && !seen.includes(value)) seen.push(value);
  }
  return seen;
}

export const jobSkills: string[] = [...new Set(jobs.flatMap((job) => job.skills))].sort((a, b) => a.localeCompare(b));
